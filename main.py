# =====================================================
# ПРОСТИЙ ПРИКЛАД ДЛЯ НОВАЧКІВ (З НУЛЯ)
# ESP32 + КНОПКА + MicroPython
# =====================================================


# -----------------------------------------------------
# IMPORT — ПІДКЛЮЧАЄМО ГОТОВІ ІНСТРУМЕНТИ
# -----------------------------------------------------

# import — це означає "взяти готовий інструмент"
# machine — це модуль для роботи з залізом ESP32
# Pin — це клас для роботи з ніжками (GPIO)
from machine import Pin

# time — модуль для роботи з часом
# він дозволяє робити паузи (sleep)
import time


# -----------------------------------------------------
# ЗМІННІ — ЦЕ КОРОБОЧКИ З ДАНИМИ
# -----------------------------------------------------

# BUTTON_PIN — це змінна
# всередині неї лежить число 4
# 4 означає GPIO4 на платі ESP32
BUTTON_PIN = 4


# -----------------------------------------------------
# КЛАС І ОБʼЄКТ
# -----------------------------------------------------

# Pin — це КЛАС (шаблон, інструкція)
# з нього ми створюємо ОБʼЄКТИ

# button — це ОБʼЄКТ
# реальна "кнопка" в коді
button = Pin(
    BUTTON_PIN,      # GPIO4 — куди фізично підключена кнопка
    Pin.IN,          # IN означає ВХІД (ми ЧИТАЄМО кнопку)
    Pin.PULL_UP      # PULL_UP означає:
                      # кнопка НЕ натиснута → 1
                      # кнопка НАТИСНУТА → 0
)


# -----------------------------------------------------
# ЗАПАМʼЯТОВУЄМО СТАН КНОПКИ
# -----------------------------------------------------

# last_state — змінна
# в ній ми зберігаємо ПОПЕРЕДНІЙ стан кнопки
# button.value() читає кнопку і повертає 0 або 1
last_state = button.value()


# -----------------------------------------------------
# ПРОСТО ТЕКСТ В ТЕРМІНАЛІ
# -----------------------------------------------------

print("Готово ✅ Натискай кнопку")


# -----------------------------------------------------
# ГОЛОВНИЙ ЦИКЛ
# -----------------------------------------------------

# while True означає:
# робити це ЗАВЖДИ
# ESP32 ніколи не зупиняється
while True:

    # current_state — змінна
    # тут ми зберігаємо ПОТОЧНИЙ стан кнопки
    # 0 = кнопка натиснута
    # 1 = кнопка відпущена
    current_state = button.value()

    # if — це перевірка
    # якщо кнопка змінилась
    if current_state != last_state:

        # робимо маленьку паузу
        # бо кнопка фізично "дрижить"
        time.sleep_ms(30)

        # читаємо кнопку ще раз
        current_state = button.value()

        # якщо стан справді змінився
        if current_state != last_state:

            # якщо кнопка натиснута
            if current_state == 0:
                print("Кнопка натиснута")

            # якщо кнопка відпущена
            else:
                print("Кнопка відпущена")

            # оновлюємо попередній стан
            last_state = current_state

    # маленька пауза, щоб ESP32 працювала стабільно
    time.sleep_ms(10)
